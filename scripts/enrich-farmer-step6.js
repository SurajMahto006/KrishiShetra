// Synchronize all keys across en, hi, mr
function syncKeys(target, ref, fallbackLang = 'en') {
  for (const cat of Object.keys(ref)) {
    if (!target[cat]) target[cat] = {};
    for (const key of Object.keys(ref[cat])) {
      if (typeof ref[cat][key] === 'object' && !Array.isArray(ref[cat][key])) {
        if (!target[cat][key]) target[cat][key] = {};
        syncKeys(target[cat][key], ref[cat][key], fallbackLang);
      } else {
        if (target[cat][key] === undefined) {
          target[cat][key] = en[cat]?.[key] || key;
        }
      }
    }
  }
}

